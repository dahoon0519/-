import { writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

// Netlify exposes CONTEXT and REVIEW_ID at BUILD time, not as automatic
// runtime variables in Netlify Functions. Compile a small non-secret file
// that the bundled function can use to choose a safe Blob namespace.
const context = (process.env.CONTEXT || (process.env.NETLIFY ? '' : 'dev')).trim();
const supported = new Set(['production', 'deploy-preview', 'branch-deploy', 'preview-server', 'dev']);
if (!supported.has(context)) {
  throw new Error('Missing or unsupported Netlify deploy CONTEXT. Refusing unsafe build.');
}

// Production must not deploy new media-editing code without the exact three
// runtime credentials required by the Cloudinary signing endpoint. Netlify
// includes these keys in the build environment when their scope includes Builds.
// Fail before generating artifacts; never print credential values.
if (context === 'production') {
  for (const name of ['CLOUDINARY_CLOUD_NAME', 'CLOUDINARY_API_KEY', 'CLOUDINARY_API_SECRET']) {
    if (!process.env[name]?.trim()) {
      throw new Error(`Production build blocked: missing ${name}. Configure the production Netlify environment before merging.`);
    }
  }
}

let namespace = null;
if (context === 'deploy-preview') {
  const reviewId = (process.env.REVIEW_ID || '').trim();
  if (!/^[1-9][0-9]*$/.test(reviewId)) {
    throw new Error('Deploy Preview lacks a valid REVIEW_ID. Refusing unsafe build.');
  }
  namespace = `preview-pr${reviewId}`;
} else if (context === 'branch-deploy' || context === 'preview-server') {
  const identity = (process.env.BRANCH || process.env.HEAD || process.env.DEPLOY_ID || '').trim();
  if (!identity) throw new Error('Missing branch/deploy identity. Refusing unsafe build.');
  namespace = `nonprod-${createHash('sha256').update(identity).digest('hex').slice(0,16)}`;
}

if (namespace && !/^[a-z0-9-]{1,32}$/.test(namespace)) {
  throw new Error('Invalid isolated storage namespace.');
}

const source = `// Non-secret generated build metadata. Regenerated by npm run build.
// Never edit manually or use this for authentication.
export const BUILD_DEPLOY_CONTEXT: string = ${JSON.stringify(context)};
export const BUILD_STORAGE_NAMESPACE: string | null = ${namespace === null ? 'null' : JSON.stringify(namespace)};
export const BUILD_COMMIT_SHA: string | null = ${/^[0-9a-f]{40}$/.test(process.env.COMMIT_REF || '') ? JSON.stringify(process.env.COMMIT_REF) : 'null'};
`;
writeFileSync(new URL('../server/deployContext.ts', import.meta.url), source, 'utf8');
console.log(`Portfolio storage build context: ${context} (${namespace ? 'isolated' : 'original/local'}).`);
